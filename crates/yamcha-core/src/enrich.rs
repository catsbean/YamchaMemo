//! 책 정보 자동 보강 보조: 제목·소개 텍스트에서 분야(장르)를 추정한다.
//! 카카오 책 API는 장르를 제공하지 않으므로, 키워드 규칙으로 분야를 제안한다.

/// 제목 + 소개에서 분야를 추정. 매칭이 없으면 None.
/// 앞쪽 항목이 우선순위가 높다 (구체적 분야 먼저).
pub fn suggest_genre(title: &str, intro: &str) -> Option<String> {
    let hay = format!("{title} {intro}");
    const TABLE: &[(&str, &[&str])] = &[
        (
            "종교/신학",
            &[
                "신학", "성경", "기독교", "예수", "하나님", "교회", "불교", "기도",
                "목회", "선교", "신앙",
            ],
        ),
        (
            "컴퓨터/IT",
            &[
                "프로그래밍", "프로그래머", "소프트웨어", "알고리즘", "코딩", "코드",
                "네트워크", "리팩터", "파이썬", "자바", "데이터베이스", "개발자",
            ],
        ),
        (
            "경제/경영",
            &[
                "경제", "경영", "투자", "주식", "부동산", "마케팅", "비즈니스",
                "재테크", "창업", "회계",
            ],
        ),
        (
            "자기계발",
            &["자기계발", "습관", "성공", "동기부여", "목표", "성장", "마인드셋"],
        ),
        (
            "심리",
            &["심리", "정신", "트라우마", "우울", "불안", "감정", "치유"],
        ),
        (
            "역사",
            &["역사", "조선", "고려", "전쟁", "왕조", "근대사", "문명", "제국"],
        ),
        (
            "과학",
            &["과학", "물리", "우주", "생물", "진화", "화학", "천문", "뇌과학"],
        ),
        ("철학", &["철학", "사상", "윤리", "형이상학", "존재론"]),
        ("예술", &["미술", "음악", "디자인", "예술", "건축", "사진", "영화"]),
        (
            "건강/의학",
            &["건강", "운동", "다이어트", "의학", "질병", "면역", "영양"],
        ),
        ("육아/교육", &["육아", "자녀", "교육", "학습", "교실", "아이"]),
        ("에세이", &["에세이", "산문", "위로", "일상"]),
        ("시", &["시집", "시인"]),
        (
            "소설/문학",
            &["소설", "장편", "단편", "문학", "이야기", "연작"],
        ),
    ];
    for (genre, kws) in TABLE {
        if kws.iter().any(|k| hay.contains(k)) {
            return Some(genre.to_string());
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn genre_from_keywords() {
        assert_eq!(
            suggest_genre("중동의 눈으로 본 예수", "성경 신학 이야기"),
            Some("종교/신학".to_string())
        );
        assert_eq!(
            suggest_genre("클린 코드", "좋은 소프트웨어를 만드는 프로그래밍 원칙"),
            Some("컴퓨터/IT".to_string())
        );
        assert_eq!(
            suggest_genre("함께 자라기", "애자일 함께 성장하는 습관"),
            Some("자기계발".to_string())
        );
        assert_eq!(suggest_genre("무제", ""), None);
    }
}
